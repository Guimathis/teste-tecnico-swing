    private void carregarTabelaFuncionarios() {
        DefaultTableModel model = (DefaultTableModel) tblFuncionarios.getModel();
        model.setRowCount(0);
        try {
            List<Funcionario> funcionarios = funcionarioController.listarTodos();
            for (Funcionario f : funcionarios) {
                model.addRow(new Object[]{
                    f.getId(),
                    f.getNome(),
                    f.getDataAdmissao().format(DATE_FMT),
                    CURRENCY_FMT.format(f.getSalario()),
                    f.isStatus()
                });
            }
        } catch (DatabaseException ex) {
            IconUtils.showError(this, ex.getMessage(), "Erro ao Carregar Funcionários");
        }
    }

    private UUID obterIdSelecionado() {
        int selectedRow = tblFuncionarios.getSelectedRow();
        if (selectedRow < 0) {
            return null;
        }
        Object value = tblFuncionarios.getValueAt(selectedRow, 0);
        if (value instanceof UUID uuid) {
            return uuid;
        }
        return UUID.fromString(value.toString());
    }

